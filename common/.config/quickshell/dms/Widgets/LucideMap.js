var _warned = {};

function resolveLigature(name) {
    if (!name)
        return "";
    if (MATERIAL_TO_LUCIDE[name])
        return MATERIAL_TO_LUCIDE[name];
    if (NATIVE[name])
        return name;
    var kebab = String(name).replace(/_/g, "-");
    if (NATIVE[kebab])
        return kebab;
    if (!_warned[name]) {
        _warned[name] = 1;
        console.warn("IconPack lucide: unmapped icon", name);
    }
    return "circle-help";
}

function resolve(name) {
    var lig = resolveLigature(name);
    var cp = NATIVE[lig];
    if (cp)
        return String.fromCharCode(cp);
    return lig;
}

function hasGlyph(name) {
    if (!name)
        return false;
    if (MATERIAL_TO_LUCIDE[name] || NATIVE[name])
        return true;
    var kebab = String(name).replace(/_/g, "-");
    return !!NATIVE[kebab];
}

function opticalScale(name) {
    var lig = resolveLigature(name);
    if (!lig)
        return 1;
    var s = Optical.SCALE[lig];
    return s === undefined ? 1 : s;
}
